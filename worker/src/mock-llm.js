function extractQuote(answer, dimensionIndex) {
  // Pick a short real substring so evidence_quote validation always passes.
  // In production this comes from the LLM; here we slice a sentence-sized chunk.
  const sentences = answer.match(/[^.!?\n]+[.!?]?/g) ?? [];
  const idx = dimensionIndex % Math.max(sentences.length, 1);
  const raw = sentences[idx]?.trim() ?? '';
  // Return null for every third dimension to exercise the null code path
  if (dimensionIndex % 3 === 2 || raw.length < 10) return null;
  return raw.length > 120 ? raw.slice(0, 120) : raw;
}

